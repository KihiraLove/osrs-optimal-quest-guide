"""Render the checked-in Markdown trackers from the local coverage inventories."""

import argparse
from collections import Counter
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
DOCS = ROOT / "docs"
STATUS = {
    "expected": "Pending",
    "collected": "Added",
    "reviewed": "Reviewed",
    "excluded": "Excluded",
}


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def counts(rows):
    totals = Counter(row["status"] for row in rows)
    return ", ".join(f"{totals[key]} {label.lower()}" for key, label in STATUS.items())


def cell(value):
    return str(value).replace("|", r"\|").replace("\n", " ").strip()


def table(columns, rows):
    lines = [
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join("---" for _ in columns) + " |",
    ]
    lines.extend("| " + " | ".join(map(cell, row)).rstrip() + " |" for row in rows)
    return "\n".join(lines)


def inventory(title, rows, labels):
    return "\n".join((
        f"## {title}",
        "",
        counts(rows) + ".",
        "",
        table(("#", *labels, "Status", "Exclusion reason"), (
            (number, *(field(row) for field in labels.values()), STATUS[row["status"]], row.get("reason", ""))
            for number, row in enumerate(rows, 1)
        )),
        "",
    ))


def header(title, ledger_path, ledger, other_tracker):
    relative = ledger_path.relative_to(ROOT).as_posix()
    return f"""# {title}

Generated by [render_activity_tracker.py](../tools/render_activity_tracker.py).
This view reads the [coverage ledger](../{relative}) for
`{ledger["dataset_version"]}` at `{ledger["game_revision"]}`.
Edit the source inventory, then run `python tools/render_activity_tracker.py`.

**Pending** means the ledger expects a catalog entry. **Added** means collected
as draft data. **Reviewed** means the ledger records an independent review.
**Excluded** records the reason. Row numbers help with scanning. Use the
canonical ID for assignments and references.

[Contributor guide](adding-activities.md) · {other_tracker}
"""


def render_activities(ledger_path, ledger, entries, reward_registry, regions):
    journal = entries["journal"]
    activity_names = {row["id"]: row["name"] for row in journal}
    return "\n".join((
        header("Activity tracker", ledger_path, ledger, "[Diary tracker](diary-tracker.md)"),
        "## Overview",
        "",
        table(("Inventory", "Coverage"), (
            ("[Journal](#journal)", counts(journal)),
            ("[Optional activities](#optional-activities)", counts(entries["optional_activities"])),
            ("[Diary tiers](diary-tracker.md#tiers)", counts([tier for region in regions for tier in region["tiers"]])),
            ("[Diary tasks](diary-tracker.md#tasks-by-region)", counts([
                task for region in regions for tier in region["tiers"] for task in tier["tasks"]
            ])),
            ("[Reward reviews](#reward-reviews)", counts(entries["reward_reviews"])),
            ("[Reward packages and claims](#reward-packages-and-claims)", counts(reward_registry)),
        )),
        "",
        "Journal entries include quests, Recipe for Disaster subquests and miniquests.",
        "Optional activities include museum, transport and other unlocks.",
        "The coverage reviews and the raw reward registry track separate work. Their rows can overlap.",
        "",
        inventory("Journal", journal, {
            "Activity": lambda row: row["name"],
            "Kind": lambda row: row["kind"],
            "ID": lambda row: f'`{row["id"]}`',
        }),
        inventory("Optional activities", entries["optional_activities"], {
            "Activity": lambda row: row["name"],
            "ID": lambda row: f'`{row["id"]}`',
        }),
        inventory("Reward reviews", entries["reward_reviews"], {
            "Activity": lambda row: activity_names.get(row.get("activity_id"), row.get("activity_id") or ""),
            "ID": lambda row: f'`{row["id"]}`',
        }),
        inventory("Reward packages and claims", reward_registry, {
            "Activity": lambda row: activity_names.get(row.get("activity_id"), row.get("activity_id") or ""),
            "ID": lambda row: f'`{row["id"]}`',
        }),
    ))


def render_diaries(ledger_path, ledger, regions):
    tiers = [tier for region in regions for tier in region["tiers"]]
    sections = [
        header("Achievement diary tracker", ledger_path, ledger, "[Activity tracker](activity-tracker.md)"),
        "Each tier lists its tracked NPC claim ID. Use the task ID to find its",
        "helper definitions and registration candidates in the",
        "[pinned diary observations](../data/raw/build-242/diaries/index.json).",
        "The tracker uses the helper condition where the ledger has no task name.",
        "",
        inventory("Tiers", tiers, {
            "Tier": lambda row: row["name"],
            "Tier ID": lambda row: f'`{row["id"]}`',
            "Claim ID": lambda row: f'`{row["reward_claim_id"]}`',
            "Tasks": lambda row: counts(row["tasks"]),
        }),
        "## Tasks by region",
        "",
    ]
    task_number = 1
    for region in regions:
        tasks = [(tier["name"], task) for tier in region["tiers"] for task in tier["tasks"]]
        sections.extend((
            f'### {region["name"]}',
            "",
            table(("#", "Tier", "Helper condition", "Task ID", "Status"), (
                (number, tier, f'`{task["condition"]}`', f'`{task["id"]}`', STATUS[task["status"]])
                for number, (tier, task) in enumerate(tasks, task_number)
            )),
            "",
        ))
        task_number += len(tasks)
    return "\n".join(sections)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if a checked-in tracker needs regeneration.")
    args = parser.parse_args()

    manifest = read_json(DATA / "manifest.json")
    ledger_path = DATA / manifest["coverage_ledger"]
    ledger = read_json(ledger_path)
    entries = {kind: read_json(ledger_path.parent / path) for kind, path in ledger["entries"].items()}
    registry = read_json(ROOT / ledger["quest_collection"]["reward_registry"])
    rewards = registry["entries"] + registry["exclusions"]
    regions = entries["diaries"]["regions"]
    documents = {
        "activity-tracker.md": render_activities(ledger_path, ledger, entries, rewards, regions),
        "diary-tracker.md": render_diaries(ledger_path, ledger, regions),
    }
    stale = []
    for filename, content in documents.items():
        path = DOCS / filename
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            if args.check:
                stale.append(f"docs/{filename}")
            else:
                path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        parser.exit(1, f"Regenerate {', '.join(stale)} with python tools/render_activity_tracker.py\n")


if __name__ == "__main__":
    main()
